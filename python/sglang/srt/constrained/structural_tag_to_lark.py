"""Translate an xgrammar-native structural tag into an llguidance Lark grammar.

The Kimi-K3 tool-call constraint is built as an xgrammar ``Format`` tree
(``function_call/kimik3_structural_tag.py``) and serialized on the wire as
``{"type": "structural_tag", "format": {...}}`` (see ``protocol.py`` calling
``StructuralTag.model_dump(by_alias=True)``). xgrammar compiles that tree with a
token-level ``TagDispatch`` primitive that has no GBNF/Lark equivalent, so the
llguidance backend cannot consume it directly.

This module walks the *serialized* Format tree (plain dicts, no llguidance or
xgrammar import needed) and emits an llguidance-native Lark grammar. Both the
strict path (``tool_choice=required`` / ``SGLANG_TOOL_STRICT_LEVEL`` >= FUNCTION)
and the auto path (``tool_choice=auto``) now build their suffix from the same
Lark-expressible nodes -- ``sequence``, ``or``, ``optional``, ``star``, ``tag``,
``tags_with_separator``, ``const_string``, ``regex``, ``json_schema``,
``any_text`` -- and both terminate the assistant turn with a mandatory
``<|close|>message<|sep|>`` so the grammar exhausts and llguidance forces EOS
(the auto path's non-terminating ``triggered_tags`` node was removed at the
source in ``kimik3_structural_tag.py``; see ``_auto_suffix`` there). The K3
markers (``<|open|>``/``<|sep|>``/``<|close|>``) are emitted as atomic
special-token references so the decode mask admits the exact token the model
produces.

The only token-level nodes this module still sees come from the heuristic
``get_kimik3_auto_tool_call_structural_tag`` entry (``any_tokens``,
``exclude_token``, ``token``); those get a best-effort lazy-lexeme approximation.

Notes on content modelling:
  * ``qwen_xml`` / ``any_text`` raw strings are modelled as a run of content
    bytes (``_CONTENT_BYTE`` = ``[^\x00]``); the atomic end marker delimits the
    value, so the string may contain a literal ``<`` (source code, HTML, ``i <
    n``, ...). Crucially the run must NOT exclude ``<``: K3 markers arrive as
    *atomic* special tokens, never as the byte ``<``, so a byte-regex terminal
    can never match a marker anyway -- but excluding ``<`` would mask every
    ordinary token that spells one (``List<T>``, ``#include <...>``), stranding
    the model off-distribution until it hits ``max_tokens``.
  * ``minLength`` / ``maxLength`` on a qwen_xml string become a regex length
    approximation; other numeric string facets rely on post-hoc validation.
    A bound above ``max_enforced_string_length`` is dropped, here and inside
    embedded ``%json`` schemas: llguidance lexes a counted repetition
    ``{0,N}`` as a fresh DFA state per generated byte, so a large bound (e.g. a
    ``write_file`` content ``maxLength: 100000``) slows every mask fill and runs
    into ``max_lexer_states`` mid-generation. Below the bound the mask is
    identical to the unbounded run, so dropping it only stops forcing the
    value closed at the limit.
  * ``any_text`` ``excludes`` are ignored (the markers are atomic special
    tokens, which a byte-regex content run can never match anyway).
"""

import json
import logging
from typing import Any, Callable, Dict, List, Optional

logger = logging.getLogger(__name__)


def structural_tag_to_lark(
    tag: Dict[str, Any], *, max_enforced_string_length: Optional[int] = None
) -> str:
    """Translate a serialized ``{type, format}`` structural tag into Lark text.

    ``max_enforced_string_length``: string ``minLength``/``maxLength`` bounds
    above it are dropped (see the module notes); ``None`` enforces every bound.
    """
    builder = _LarkBuilder(max_enforced_string_length)
    start_ref = builder.emit(tag["format"])
    # One aggregate log per unique schema (BaseGrammarBackend caches the
    # compiled grammar, so a given schema is translated once). Per-keyword
    # logging would be unbounded -- a single schema can carry tens of
    # thousands of occurrences in prod traffic.
    if builder._relaxed:
        logger.warning(
            "structural_tag_to_lark: relaxed %d llguidance-unsupported "
            "JSON-schema keyword(s) (not/uniqueItems/if-then-else/contains/"
            "propertyNames/oneOf) to let the surviving constraints compile",
            builder._relaxed,
        )
    if builder._dropped_length_bounds:
        logger.warning(
            "structural_tag_to_lark: dropped %d string minLength/maxLength "
            "bound(s) above %d (SGLANG_LLGUIDANCE_MAX_ENFORCED_STRING_LENGTH); "
            "those lengths are not enforced at decode time",
            builder._dropped_length_bounds,
            max_enforced_string_length,
        )
    if builder._clamped_max_items:
        logger.warning(
            "structural_tag_to_lark: clamped %d array maxItems bound(s) to %d "
            "so the llguidance compile does not exhaust memory",
            builder._clamped_max_items,
            _MAX_ENFORCED_ITEMS,
        )
    return "\n".join([f"start: {start_ref}", *builder.rules])


# llguidance 1.8.0's ``%json{...}`` inline compiler fails *closed* on a handful
# of JSON-schema draft keywords (``failed to compile JSON schema: Unimplemented
# keys: [...]``), aborting the whole structural_tag with an HTTP 400. xgrammar
# (the default backend) is unaffected -- it hands the schema to its C++ engine,
# which enforces ``not`` and ignores ``uniqueItems`` rather than erroring. To
# match that fail-*open* behaviour we strip the unsupported keywords out of the
# embedded ``%json`` schema before handing it to llguidance; the surviving
# siblings still compile and stay enforced. Stripping is node-local: removing a
# keyword relaxes only that one constraint, never a sibling or parent. ``not``
# is relaxed, not truly enforced (real negation would need either a patched
# llguidance or a hand-built property grammar -- large effort, low value).
_LLG_DROP_SCALAR = ("uniqueItems",)
_LLG_DROP_SUBSCHEMA = ("not", "propertyNames")
_LLG_DROP_GROUPS = (
    ("if", "then", "else"),
    ("contains", "minContains", "maxContains"),
)
# Subschema positions to recurse into after stripping. Mirrors the lists in
# ``function_call/utils.py:114-133`` but kept local so this module stays a pure
# dict->str translator with no cross-module import.
_SUBSCHEMA_MAP_KEYS = (
    "properties",
    "patternProperties",
    "$defs",
    "definitions",
    "dependentSchemas",
)
_SUBSCHEMA_LIST_KEYS = ("anyOf", "allOf", "prefixItems")
_SUBSCHEMA_SINGLE_KEYS = (
    "items",
    "additionalProperties",
    "unevaluatedItems",
    "unevaluatedProperties",
)
_MISSING = object()


def _relax_for_llguidance(schema: Any) -> int:
    """Strip llguidance-unsupported keywords in place; return the count removed.

    In-place mutation is safe because the schema tree is single-use: production
    parses it fresh via ``json.loads`` in ``llguidance_backend.py`` for each
    request, and tests pass a fresh ``model_dump``. Strip-then-descend so a
    dropped keyword's subtree is never visited; recurse only into genuine
    subschema positions so data keywords (``const``/``enum``/``default``) stay
    intact.
    """
    if isinstance(schema, list):
        return sum(_relax_for_llguidance(item) for item in schema)
    if not isinstance(schema, dict):
        return 0
    removed = 0
    if "oneOf" in schema:  # XOR -> OR: alternatives stay enforced, exclusivity drops.
        one_of = schema.pop("oneOf")
        schema.setdefault("anyOf", one_of)
        removed += 1
    for key in _LLG_DROP_SCALAR + _LLG_DROP_SUBSCHEMA:
        if schema.pop(key, _MISSING) is not _MISSING:
            removed += 1
    for group in _LLG_DROP_GROUPS:
        if group[0] in schema:
            for key in group:
                if schema.pop(key, _MISSING) is not _MISSING:
                    removed += 1
    return removed + sum(
        _relax_for_llguidance(value) for value in _child_subschemas(schema)
    )


def _child_subschemas(schema: Dict[str, Any]):
    """Yield the subschemas nested directly under ``schema``."""
    for key in _SUBSCHEMA_MAP_KEYS:
        nested = schema.get(key)
        if isinstance(nested, dict):
            yield from nested.values()
    for key in _SUBSCHEMA_LIST_KEYS:  # anyOf now also carries any former oneOf.
        nested = schema.get(key)
        if isinstance(nested, list):
            yield from nested
    for key in _SUBSCHEMA_SINGLE_KEYS:
        if key in schema:
            yield schema[key]


_STRING_LENGTH_KEYS = ("minLength", "maxLength")


def _is_oversized_length(value: Any, max_enforced: Optional[int]) -> bool:
    return (
        max_enforced is not None
        and isinstance(value, int)
        and not isinstance(value, bool)
        and value > max_enforced
    )


def _drop_oversized_string_lengths(schema: Any, max_enforced: Optional[int]) -> int:
    """Drop ``minLength``/``maxLength`` above ``max_enforced`` in place.

    Same in-place/single-use contract and subschema walk as
    ``_relax_for_llguidance``; returns the count dropped.
    """
    if max_enforced is None:
        return 0
    if isinstance(schema, list):
        return sum(_drop_oversized_string_lengths(item, max_enforced) for item in schema)
    if not isinstance(schema, dict):
        return 0
    removed = 0
    for key in _STRING_LENGTH_KEYS:
        if _is_oversized_length(schema.get(key), max_enforced):
            del schema[key]
            removed += 1
    return removed + sum(
        _drop_oversized_string_lengths(value, max_enforced)
        for value in _child_subschemas(schema)
    )


# llguidance 1.8.0 compiles an array's ``maxItems`` by unrolling one grammar
# symbol per allowed item, before checking ``max_grammar_size``. A tool schema
# with ``maxItems: 2147483647`` therefore grows the compile past several GB
# within seconds and OOMs the scheduler. Clamp it so a bad schema can at worst
# fail its own request: on 1.8.0 this bound still overflows the compiler's u16
# symbol table and the request gets a 400; llguidance >= 1.9.0 compiles bounded
# array tails compactly and enforces it.
_MAX_ENFORCED_ITEMS = 100_000


def _clamp_oversized_max_items(schema: Any) -> int:
    """Clamp ``maxItems`` above ``_MAX_ENFORCED_ITEMS`` in place.

    Same in-place/single-use contract and subschema walk as
    ``_relax_for_llguidance``; returns the count clamped.
    """
    if isinstance(schema, list):
        return sum(_clamp_oversized_max_items(item) for item in schema)
    if not isinstance(schema, dict):
        return 0
    clamped = 0
    max_items = schema.get("maxItems")
    if (
        isinstance(max_items, int)
        and not isinstance(max_items, bool)
        and max_items > _MAX_ENFORCED_ITEMS
    ):
        schema["maxItems"] = _MAX_ENFORCED_ITEMS
        clamped += 1
    return clamped + sum(
        _clamp_oversized_max_items(value) for value in _child_subschemas(schema)
    )


_LARK_STRING_ESCAPES = {
    "\\": "\\\\",
    '"': '\\"',
    "\n": "\\n",
    "\t": "\\t",
    "\r": "\\r",
}


def _lark_string_literal(value: str) -> str:
    """Render ``value`` as a double-quoted Lark literal.

    Escapes ``\\`` and ``"``, and renders control characters as Lark escape
    sequences. A literal newline/tab inside a ``"..."`` terminal is a lexer
    error, so an enum/const string value carrying one (e.g. an enum member that
    is a bare ``"\\n"``) would otherwise fail the whole structural_tag compile.
    """
    out: List[str] = []
    for ch in value:
        escape = _LARK_STRING_ESCAPES.get(ch)
        if escape is not None:
            out.append(escape)
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append(f"\\u{ord(ch):04x}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def _lark_regex(pattern: str) -> str:
    """Render ``pattern`` as an inline ``/.../`` Lark terminal."""
    return "/" + pattern.replace("/", r"\/") + "/"


# K3's atomic wire markers. Each has a dedicated special-token id, so the model
# (and the speculative draft) emit them as a single token, not as their five/six
# constituent bytes. Referencing them as quoted byte literals makes llguidance
# enforce canonical tokenization and admit only the first byte segment (``<``) at
# a boundary, masking out the atomic id; a bare ``<|open|>`` reference asks for
# exactly the special token instead. Every other marker word (``tools``,
# ``call``, ``argument``, ...) is ordinary text between these three.
_SPECIAL_MARKERS = ("<|open|>", "<|sep|>", "<|close|>")


def _split_markers(value: str) -> List[tuple]:
    """Split ``value`` into ``("special", marker)`` / ``("text", chunk)`` pieces."""
    pieces: List[tuple] = []
    i = 0
    while i < len(value):
        marker = None
        pos = len(value)
        for candidate in _SPECIAL_MARKERS:
            found = value.find(candidate, i)
            if found != -1 and found < pos:
                pos, marker = found, candidate
        if marker is None:
            pieces.append(("text", value[i:]))
            break
        if pos > i:
            pieces.append(("text", value[i:pos]))
        pieces.append(("special", marker))
        i = pos + len(marker)
    return pieces


def _marker_atoms(value: str) -> str:
    """Render a marker-bearing literal as space-joined Lark atoms.

    K3 special markers become bare special-token references (``<|open|>``); the
    surrounding bytes stay quoted literals. An empty string keeps the empty
    literal the callers already relied on (e.g. a ``TagFormat`` with no prefix).
    """
    if value == "":
        return '""'
    return " ".join(
        marker if kind == "special" else _lark_string_literal(marker)
        for kind, marker in _split_markers(value)
    )


# A run of free content bytes. K3's wire markers arrive as *atomic* special
# tokens (``<|open|>``/``<|sep|>``/``<|close|>`` -> dedicated ids), never as the
# byte ``<``, and a byte-regex terminal can never match a special token. So a
# content run must NOT exclude ``<``: doing so masks every token that spells one
# (generics ``List<T>``, comparisons ``i < n``, ``#include <...>``, ``<summary>``)
# and, inside a tool-argument value, strands the model off-distribution -- it can
# no longer write the ``<`` its code needs, never converges on the closing marker,
# and runs to ``max_tokens``. The atomic end marker still delimits the run
# unambiguously, so admitting every (non-NUL) byte is safe.
_CONTENT_BYTE = "[^\\x00]"


def _lazy_text() -> str:
    """Match any run of content bytes (the atomic end marker delimits it)."""
    return f"/{_CONTENT_BYTE}*/"


def _raw_scalar(value: Any) -> str:
    """The unquoted wire form of a qwen_xml scalar (string values are raw)."""
    return value if isinstance(value, str) else json.dumps(value)


class _LarkBuilder:
    """Accumulate Lark rules while walking a Format tree.

    ``emit`` returns a Lark *atom* (a rule name, a ``"literal"``, or an inline
    ``/regex/``) usable inside a rule body. Composite nodes register a fresh rule
    and return its name so nesting stays shallow and the emitted grammar reads
    top-down.
    """

    def __init__(self, max_enforced_string_length: Optional[int]) -> None:
        self.rules: List[str] = []
        self._counter = 0
        self._relaxed = 0
        self._max_enforced_string_length = max_enforced_string_length
        self._dropped_length_bounds = 0
        self._clamped_max_items = 0
        self._handlers: Dict[str, Callable[[Dict[str, Any]], str]] = {
            "const_string": self._emit_const_string,
            "regex": self._emit_regex,
            "json_schema": self._emit_json_schema,
            "any_text": self._emit_any_text,
            "tag": self._emit_tag,
            "sequence": self._emit_sequence,
            "or": self._emit_or,
            "optional": self._emit_optional,
            "star": self._emit_star,
            "tags_with_separator": self._emit_tags_with_separator,
            # Token-level nodes from the heuristic auto entry: best-effort only.
            "any_tokens": self._emit_any_tokens,
            "exclude_token": self._emit_exclude_token,
            "token": self._emit_token,
        }

    def emit(self, node: Dict[str, Any]) -> str:
        """ emit"""
        node_type = node["type"]
        handler = self._handlers.get(node_type)
        if handler is None:
            raise ValueError(f"Unsupported structural tag node: {node_type!r}")
        return handler(node)

    def _add_rule(self, body: str, hint: str) -> str:
        self._counter += 1
        name = f"r{self._counter}_{hint}"
        self.rules.append(f"{name}: {body}")
        return name

    def _emit_const_string(self, node: Dict[str, Any]) -> str:
        return _marker_atoms(node["value"])

    def _emit_regex(self, node: Dict[str, Any]) -> str:
        return _lark_regex(node["pattern"])

    def _emit_json_schema(self, node: Dict[str, Any]) -> str:
        if node.get("style") == "qwen_xml":
            return self._emit_qwen_xml_value(node["json_schema"])
        # Lark embeds a JSON schema inline; llguidance resolves $ref, prefixItems,
        # oneOf/anyOf against it directly. Relax llguidance-unsupported keywords
        # first (see ``_relax_for_llguidance``) so the schema compiles instead of
        # aborting the whole structural_tag with a 400.
        schema = node["json_schema"]
        self._relaxed += _relax_for_llguidance(schema)
        self._dropped_length_bounds += _drop_oversized_string_lengths(
            schema, self._max_enforced_string_length
        )
        self._clamped_max_items += _clamp_oversized_max_items(schema)
        return self._add_rule("%json" + json.dumps(schema), "json")

    def _emit_qwen_xml_value(self, schema: Any) -> str:
        # The K3 generator restricts the schema to ``string`` before emitting a
        # qwen_xml node, so the value is an unquoted (raw) string on the wire.
        if not isinstance(schema, dict):
            return _lazy_text()
        if "const" in schema:
            return _lark_string_literal(_raw_scalar(schema["const"]))
        enum = schema.get("enum")
        if isinstance(enum, list) and enum:
            alternatives = " | ".join(
                _lark_string_literal(_raw_scalar(value)) for value in enum
            )
            return self._add_rule(alternatives, "enum")
        pattern = schema.get("pattern")
        if isinstance(pattern, str):
            return _lark_regex(pattern)
        min_length = self._enforced_length(schema.get("minLength"))
        max_length = self._enforced_length(schema.get("maxLength"))
        if isinstance(min_length, int) or isinstance(max_length, int):
            low = min_length if isinstance(min_length, int) else 0
            high = max_length if isinstance(max_length, int) else ""
            return _lark_regex(f"{_CONTENT_BYTE}{{{low},{high}}}")
        return _lazy_text()

    def _enforced_length(self, value: Any) -> Any:
        """Return ``value`` unless it is a bound too large to enforce."""
        if _is_oversized_length(value, self._max_enforced_string_length):
            self._dropped_length_bounds += 1
            return None
        return value

    def _emit_any_text(self, node: Dict[str, Any]) -> str:
        return _lazy_text()

    def _emit_tag(self, node: Dict[str, Any]) -> str:
        begin = _marker_atoms(node["begin"])
        content = self.emit(node["content"])
        end = _marker_atoms(node["end"])
        return self._add_rule(f"{begin} {content} {end}", "tag")

    def _emit_sequence(self, node: Dict[str, Any]) -> str:
        parts = [self.emit(element) for element in node["elements"]]
        return self._add_rule(" ".join(parts), "seq")

    def _emit_or(self, node: Dict[str, Any]) -> str:
        parts = [self.emit(element) for element in node["elements"]]
        return self._add_rule(" | ".join(parts), "or")

    def _emit_optional(self, node: Dict[str, Any]) -> str:
        return self._add_rule(f"({self.emit(node['content'])})?", "opt")

    def _emit_star(self, node: Dict[str, Any]) -> str:
        return self._add_rule(f"({self.emit(node['content'])})*", "star")

    def _emit_tags_with_separator(self, node: Dict[str, Any]) -> str:
        alternatives = " | ".join(self.emit(tag) for tag in node["tags"])
        separator = node.get("separator", "")
        at_least_one = node.get("at_least_one", False)
        stop_after_first = node.get("stop_after_first", False)
        if stop_after_first:
            body = f"({alternatives})" if at_least_one else f"({alternatives})?"
        elif not separator:
            body = f"({alternatives})+" if at_least_one else f"({alternatives})*"
        else:
            sep = _lark_string_literal(separator)
            repeated = f"({alternatives}) ({sep} ({alternatives}))*"
            body = repeated if at_least_one else f"({repeated})?"
        return self._add_rule(body, "tags")

    def _emit_any_tokens(self, node: Dict[str, Any]) -> str:
        return _lazy_text()

    def _emit_exclude_token(self, node: Dict[str, Any]) -> str:
        return _lark_regex(_CONTENT_BYTE)

    def _emit_token(self, node: Dict[str, Any]) -> str:
        # A ``TokenFormat`` matches exactly one token id. K3 only uses it for the
        # ``<|close|>`` marker (the argument/call terminator), so render it as the
        # bare special-token reference rather than its byte spelling.
        return _marker_atoms(node["token"])
